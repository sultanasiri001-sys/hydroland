def digest(data):
    return hashlib.sha256(data).hexdigest()

def canonical(data):
    return json.dumps(json.loads(data), sort_keys=True, separators=(',',':')).encode()

def version18(output):
    return bool(re.search(r'\(PostgreSQL\) 18(?:\.|\s|$)', output))

def safe_env(work):
    # Do not inherit PG*, DATABASE_URL, provider credentials, HOME client configs.
    return {'PATH':os.defpath, 'HOME':str(work), 'LANG':'C', 'LC_ALL':'C',
            'PGHOST':str(work/'socket'), 'PGPORT':'55484', 'PGUSER':'a04_synthetic',
            'PGCONNECT_TIMEOUT':'5', 'PGCLIENTENCODING':'UTF8', 'PGTZ':'UTC'}

def plan(work, bins):
    # work is freshly created by this program, never a caller-supplied cluster.
    return [bins['pg_ctl'], '-D', str(work/'cluster'), '-l', str(work/'postgres.log'),
            '-o', "-c listen_addresses='' -c unix_socket_directories='"+str(work/'socket')+"' -p 55484", '-w', '-t','30','start']

def resolve_tools():
    result={name:shutil.which(name) for name in TOOLS}
    if not all(result.values()):
        raise RuntimeError('PG18_TOOLS_REQUIRED')
    for path in result.values():
        out=subprocess.run([path,'--version'],capture_output=True,timeout=10,check=True).stdout.decode()
        if not version18(out): raise RuntimeError('PG18_VERSION_REQUIRED')
    return result

def receipt():
    return {'kind':'A04_SYNTHETIC_PG18_ADDON_V1','synthetic':True,
            'realUatAcceptance':'NOT_RUN','applicationStartup':'NOT_RUN',
            'savedUatReads':0,'savedUatWrites':0,'productionWrites':0,
            'networkListeners':'UNIX_SOCKET_ONLY','actualSyntheticRestore':'NOT_RUN'}

def execute(work,bins):
    report=receipt(); started=False; stage='init'; begin=time.monotonic(); env=safe_env(work)
    def run(args, data=None, db=None):
        value=subprocess.run(args,input=data,capture_output=True,env={**env,**({'PGDATABASE':db} if db else {})},timeout=120)
        if value.returncode: raise RuntimeError('CLIENT_FAILED') # never emit raw logs/errors
        return value.stdout
    def sql(db,query):
        return run([bins['psql'],'-X','-q','-A','-t','-w','-v','ON_ERROR_STOP=1','-c',query],db=db)
    try:
        (work/'socket').mkdir(mode=0o700)
        run([bins['initdb'],'-D',str(work/'cluster'),'-U','a04_synthetic','-A','trust','--no-locale','--encoding=UTF8'])
        # Mark attempted before start: a timed-out start may nevertheless leave a server.
        started=True; run(plan(work,bins)); stage='identity'
        identity=json.loads(sql('postgres',"SELECT json_build_object('version',current_setting('server_version_num'),'data',current_setting('data_directory'),'listen',current_setting('listen_addresses'),'database',current_database());"))
        if not (180000 <= int(identity['version']) < 190000 and Path(identity['data']).resolve()==(work/'cluster').resolve() and identity['listen']=='' and identity['database']=='postgres'):
            raise RuntimeError('IDENTITY_MISMATCH')
        for db in DBS: sql('postgres','CREATE DATABASE '+db+' TEMPLATE template0;')
        stage='fixture'; sql(DBS[0],FIXTURE)
        expected=canonical(sql(DBS[0],SNAPSHOT))
        if sql(DBS[1],"SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace AND relkind IN ('r','p','v','m','S');").strip()!=b'0': raise RuntimeError('TARGET_NOT_EMPTY')
        stage='dump'; archive=work/'synthetic.dump'
        run([bins['pg_dump'],'--format=custom','--no-owner','--no-privileges','--file='+str(archive)],db=DBS[0])
        archive.chmod(0o600); before=digest(archive.read_bytes()); report['archiveSha256']=before
        if not archive.stat().st_size: raise RuntimeError('EMPTY_ARCHIVE')
        run([bins['pg_restore'],'--list',str(archive)])
        stage='restore'; run([bins['pg_restore'],'--exit-on-error','--single-transaction','--no-owner','--no-privileges','--dbname='+DBS[1],str(archive)])
        stage='compare'
        if canonical(sql(DBS[1],SNAPSHOT)) != expected or canonical(sql(DBS[0],SNAPSHOT)) != expected: raise RuntimeError('RESTORE_MISMATCH')
        # Prove comparison detects alteration; rollback makes no persistent fixture change.
        probe=sql(DBS[1],"BEGIN; UPDATE fixture_finance SET amount=amount+1 WHERE id=1; "+SNAPSHOT+" ROLLBACK;")
        if canonical(probe)==expected: raise RuntimeError('NEGATIVE_CONTROL_MISSED')
        if canonical(sql(DBS[1],SNAPSHOT))!=expected: raise RuntimeError('ROLLBACK_MISMATCH')
        if digest(archive.read_bytes())!=before: raise RuntimeError('ARCHIVE_CHANGED')
        report.update(actualSyntheticRestore='PASS',snapshotSha256=digest(expected),negativeControlDetected=True,archivePreserved=True)
    except Exception:
        report.update(actualSyntheticRestore='FAIL',failedStage=stage)
    finally:
        if started:
            try: run([bins['pg_ctl'],'-D',str(work/'cluster'),'-m','fast','-w','-t','30','stop']); report['clusterStopped']=True
            except Exception: report.update(clusterStopped=False,actualSyntheticRestore='FAIL',failedStage='stop')
        report['elapsedSeconds']=round(time.monotonic()-begin,3)
        report['scriptSha256']=digest(Path(__file__).read_bytes())
        (work/'receipt.json').write_text(json.dumps(report,indent=2)+'\n'); (work/'receipt.json').chmod(0o600)
    return report

def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--execute-approved-synthetic',action='store_true'); args=parser.parse_args()
    if not args.execute_approved_synthetic:
        print(json.dumps({**receipt(),'blocker':'EXPLICIT_SYNTHETIC_EXECUTION_APPROVAL_REQUIRED'})); return 2
    bins=resolve_tools() # no network / install / resource creation on missing prerequisites
    work=Path(tempfile.mkdtemp(prefix='a04-pg18-')).resolve(); work.chmod(0o700)
    report=execute(work,bins); print(json.dumps({'report':report,'privateWorkdir':str(work)}))
    return 0 if report['actualSyntheticRestore']=='PASS' else 1

