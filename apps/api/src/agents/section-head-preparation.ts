export function sectionPreparation(key:string){
  const section=sectionHeadFor(key);if(!section)return null;
  const duty=duties[section.code],department=departments[section.departmentCode];
  const forms=SECTION_FORM_COVERAGE.find(row=>row.code===section.code);
  if(!duty||!department||!forms||forms.department!==section.departmentCode)throw new Error('Section preparation coverage mismatch.');
  return{version:SECTION_PREPARATION_VERSION,source:SECTION_DUTY_SOURCE,sectionCode:section.code,
    directorKey:DEPARTMENT_DIRECTORS[section.departmentCode],...department,
    duties:[...duty.duties],deliverables:duty.deliverables,indicator:duty.indicator,templateCodes:[...forms.templateCodes]};
}

