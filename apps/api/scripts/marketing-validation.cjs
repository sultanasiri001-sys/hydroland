const assert=require('node:assert/strict');
const {MarketingFoundationService}=require('../.tmp-marketing-validation/marketing-foundation.service.js');
const {MarketingWorkflowService}=require('../.tmp-marketing-validation/marketing-workflow.service.js');
const {MarketingOperationsService}=require('../.tmp-marketing-validation/marketing-operations.service.js');
const {MarketingGovernanceService}=require('../.tmp-marketing-validation/marketing-governance.service.js');
const f=new MarketingFoundationService(), w=new MarketingWorkflowService(), o=new MarketingOperationsService(), g=new MarketingGovernanceService();
const audience={id:'aud-1',organizationId:'org-1',name:'Divers',segmentDefinition:'active divers',active:true};
const campaign={id:'cmp-1',organizationId:'org-1',name:'Dive campaign',status:'DRAFT',audienceId:'aud-1',channels:['APP','SOCIAL'],objective:'Bookings',startAt:new Date('2026-10-01'),endAt:new Date('2026-10-31')};
const asset={id:'asset-1',organizationId:'org-1',campaignId:'cmp-1',title:'Campaign post',contentType:'POST',language:'AR',approved:true};
f.validateCampaign(campaign,audience); f.validateContent(asset,campaign);
let req=w.requestApproval(campaign,'marketer-1'); assert.equal(req.status,'REQUESTED');
assert.throws(()=>w.decide(req,'marketer-1','APPROVED'));
let approval=w.decide(req,'manager-1','APPROVED');
let active=w.activate(campaign,approval,[asset]); assert.equal(active.status,'ACTIVE');
const source={organizationId:'org-1',type:'TRIP',id:'trip-1',exists:true,marketable:true};
const attr=o.attribution(active,source,{customerId:'cust-1',bookingId:'book-1',transactionId:'txn-1'});
assert.equal(attr.campaignId,'cmp-1');
let paused=w.pause(active); assert.equal(paused.status,'PAUSED');
let completed=w.complete(paused); assert.equal(completed.status,'COMPLETED');
assert.throws(()=>w.activate(campaign,{...approval,status:'REJECTED'},[asset]));
assert.throws(()=>w.activate(campaign,approval,[{...asset,approved:false}]));
assert.throws(()=>o.validateCampaignSource(active,{...source,organizationId:'org-2'}));
assert.throws(()=>o.validateCampaignSource(active,{...source,marketable:false}));
assert.throws(()=>o.attribution(active,source,{}));
assert.throws(()=>f.validateCampaign({...campaign,endAt:new Date('2026-09-01')},audience));
const noAttr={...active,id:'cmp-2'};
const snap=g.snapshot([active,paused,completed,noAttr],[attr]);
assert.equal(snap.campaignsWithoutAttribution,1); assert.equal(snap.pausedCampaigns,1);
const sig=g.automationSignals(snap);
assert.ok(sig.includes('REVIEW_CAMPAIGN_TRACKING')); assert.ok(sig.includes('REVIEW_PAUSED_CAMPAIGNS'));
console.log('Marketing validation passed.');