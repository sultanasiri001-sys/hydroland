const assert = require('node:assert/strict');
const { CustomerServiceFoundationService } = require('../.tmp-customer-service-validation/customer-service-foundation.service.js');
const { CustomerServiceWorkflowService } = require('../.tmp-customer-service-validation/customer-service-workflow.service.js');
const { CustomerServiceOperationsService } = require('../.tmp-customer-service-validation/customer-service-operations.service.js');
const { CustomerServiceGovernanceService } = require('../.tmp-customer-service-validation/customer-service-governance.service.js');

const foundation = new CustomerServiceFoundationService();
const workflow = new CustomerServiceWorkflowService(foundation);
const operations = new CustomerServiceOperationsService(foundation);
const governance = new CustomerServiceGovernanceService();
const base = { id:'case-1', organizationId:'org-1', customerId:'cust-1', type:'BOOKING_ISSUE', status:'OPEN', priority:'HIGH', subject:'Booking issue', description:'Unable to confirm booking', referenceType:'BOOKING', referenceId:'booking-1', createdAt:new Date('2026-09-23T00:00:00Z') };
foundation.validateCase(base);
operations.validateOperationalCase(base,{organizationId:'org-1',type:'BOOKING',id:'booking-1',exists:true,accessible:true});
let assigned=workflow.assign(base,'agent-1');
assert.equal(assigned.status,'ASSIGNED');
workflow.addInteraction(assigned,{id:'int-1',caseId:assigned.id,actorType:'STAFF',actorId:'agent-1',channel:'APP',message:'Reviewing case',createdAt:new Date()});
let waiting=workflow.waitForCustomer(assigned);
let resolved=workflow.resolve(waiting,'agent-1');
let closed=workflow.close(resolved);
assert.equal(closed.status,'CLOSED');
assert.equal(operations.escalationRoute(base),'OPERATIONS');
assert.throws(()=>workflow.assign(closed,'agent-2'));
assert.throws(()=>workflow.resolve(assigned,'wrong-agent'));
assert.throws(()=>workflow.close(assigned));
assert.throws(()=>workflow.addInteraction(closed,{id:'int-2',caseId:closed.id,actorType:'SYSTEM',channel:'SYSTEM',message:'x',createdAt:new Date()}));
assert.throws(()=>operations.validateOperationalCase(base,{organizationId:'org-2',type:'BOOKING',id:'booking-1',exists:true,accessible:true}));
assert.throws(()=>operations.validateOperationalCase(base,{organizationId:'org-1',type:'BOOKING',id:'booking-1',exists:false,accessible:true}));
const urgent={...base,id:'case-2',type:'COMPLAINT',priority:'URGENT'};
const safety={...base,id:'case-3',type:'SAFETY_CONCERN',referenceType:'SAFETY',referenceId:'safety-1'};
const snapshot=governance.snapshot([urgent,safety,closed]);
assert.equal(snapshot.urgentCases,1);
assert.equal(snapshot.unresolvedComplaints,1);
assert.equal(snapshot.safetyConcerns,1);
const signals=governance.automationSignals(snapshot);
assert.ok(signals.includes('NOTIFY_CUSTOMER_SERVICE_MANAGER'));
assert.ok(signals.includes('CREATE_COMPLAINT_FOLLOWUP'));
assert.ok(signals.includes('NOTIFY_SAFETY_MANAGEMENT'));
assert.ok(signals.includes('ASSIGN_OPEN_CASES'));
console.log('Customer Service validation passed.');
