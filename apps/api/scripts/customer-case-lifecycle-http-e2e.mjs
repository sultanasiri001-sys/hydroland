import assert from 'node:assert/strict';
import { randomBytes, scryptSync } from 'node:crypto';
import { PrismaClient } from '@prisma/client';

const base = process.env.CUSTOMER_CASE_E2E_BASE_URL || 'http://127.0.0.1:3101/api/v1';
for (const endpoint of [base, process.env.DATABASE_URL]) {
  assert(['127.0.0.1', 'localhost', '[::1]'].includes(new URL(endpoint).hostname), 'Customer-case fixtures require loopback services');
}
const db = new PrismaClient(), suffix = randomBytes(8).toString('hex');
const password = randomBytes(24).toString('hex'), salt = randomBytes(16).toString('hex');
const passwordHash = salt + ':' + scryptSync(password, salt, 64).toString('hex');
const accounts = [], organizations = [], cases = [];
const triggerName = 'case_failure_' + suffix;
let triggerInstalled = false;

async function request(actor, path, body, expected = body === undefined ? 200 : 201) {
  const response = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST',
    headers: { 'content-type': 'application/json', ...(actor?.token ? { authorization: 'Bearer ' + actor.token } : {}) },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }), signal: AbortSignal.timeout(15000) });
  const data = await response.json().catch(() => null);
  assert.equal(response.status, expected, path + ': ' + JSON.stringify(data));
  return data;
}
async function account(label, role, options = {}) {
  const created = await db.account.create({ data: { email: `case-${label}-${suffix}@example.invalid`, passwordHash,
    status: options.status || 'ACTIVE', emailVerifiedAt: options.verified === false ? null : new Date(),
    person: { create: { firstName: 'SyntheticCase', lastName: label } },
    ...(role ? { roleAssignments: { create: { role, status: 'ACTIVE' } } } : {}) } });
  accounts.push(created);
  if (created.status === 'ACTIVE' && created.emailVerifiedAt) created.token = (await request(null, '/auth/login', { email: created.email, password }, 200)).accessToken;
  return created;
}
async function createCase(actor, type = 'SUPPORT', organizationId = null) {
  const path = organizationId ? `/organizations/${organizationId}/requests` : '/customer-service/cases';
  const result = await request(actor, path, { type, subject: 'Synthetic customer case', description: 'Isolated lifecycle acceptance fixture' });
  cases.push(result.id); return result;
}
const management = id => '/customer-service/admin/cases/' + id;
const responsePath = (id, organizationId) => organizationId ? `/organizations/${organizationId}/requests/${id}/resolution-response` : `/customer-service/cases/${id}/resolution-response`;
const deadline = () => new Date(Date.now() + 2 * 86400000).toISOString();
const state = id => db.customerCase.findUniqueOrThrow({ where: { id }, include: { interactions: { orderBy: [{ createdAt: 'asc' }, { id: 'asc' }] } } });
const auditCount = (id, action) => db.auditEvent.count({ where: { resource: 'CustomerCase', resourceId: id, ...(action ? { action } : {}) } });
async function injectAuditFailure(caseId, action) {
  // Both identifiers and the case ID are generated by this isolated fixture.
  await db.$executeRawUnsafe(`CREATE OR REPLACE FUNCTION "${triggerName}"() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW."resource"='CustomerCase' AND NEW."resourceId"='${caseId}' AND NEW."action"='${action}' THEN RAISE EXCEPTION 'SYNTHETIC_CASE_AUDIT_FAILURE'; END IF; RETURN NEW; END $$`);
  if (!triggerInstalled) {
    await db.$executeRawUnsafe(`CREATE TRIGGER "${triggerName}" BEFORE INSERT ON "AuditEvent" FOR EACH ROW EXECUTE FUNCTION "${triggerName}"()`);
    triggerInstalled = true;
  }
}
async function clearAuditFailure() {
  if (triggerInstalled) await db.$executeRawUnsafe(`DROP TRIGGER "${triggerName}" ON "AuditEvent"`);
  triggerInstalled = false;
  await db.$executeRawUnsafe(`DROP FUNCTION IF EXISTS "${triggerName}"()`);
}

try {
  const admin = await account('admin', 'ADMIN'), peer = await account('peer', 'ADMIN');
  const customer = await account('requester'), other = await account('other'), staff = await account('staff', 'STAFF');
  const suspended = await account('suspended', 'ADMIN', { status: 'SUSPENDED' });
  const unverified = await account('unverified', 'ADMIN', { verified: false });
  const org = await db.organization.create({ data: { displayName: 'Case fixture ' + suffix, kind: 'DIVE_CENTER', status: 'ACTIVE', ownerId: customer.id,
    members: { create: [{ accountId: customer.id, role: 'OWNER', status: 'ACTIVE' }, { accountId: other.id, role: 'STAFF', status: 'ACTIVE' }] } } });
  organizations.push(org);
  const orgB = await db.organization.create({ data: { displayName: 'Other case fixture ' + suffix, kind: 'DIVE_CENTER', status: 'ACTIVE', ownerId: staff.id,
    members: { create: { accountId: staff.id, role: 'OWNER', status: 'ACTIVE' } } } });
  organizations.push(orgB);

  const ordinary = await createCase(customer, 'PAYMENT_ISSUE'), id = ordinary.id, path = management(id);
  await request(null, '/customer-service/admin/cases', undefined, 401);
  await request(customer, '/customer-service/admin/cases', undefined, 403);
  await request(staff, path, undefined, 403);
  await request(customer, '/customer-service/admin/cases/assignees', undefined, 403);
  const assignees = await request(admin, '/customer-service/admin/cases/assignees');
  assert(assignees.some(row => row.id === admin.id && row.displayName));
  assert(!assignees.some(row => [staff.id, suspended.id, unverified.id, customer.id].includes(row.id)));
  await request(customer, path + '/assign', { assignedAccountId: admin.id, dueAt: deadline() }, 403);
  for (const assignee of [customer, staff, suspended, unverified]) {
    await request(admin, path + '/assign', { assignedAccountId: assignee.id, dueAt: deadline() }, 403);
  }
  for (const dueAt of [undefined, 'tomorrow', '2030-01-01T10:00:00', '2032-02-30T12:00:00Z', '2032-06-31T12:00:00Z', '2032-01-01T24:00:00Z', new Date(Date.now() - 1000).toISOString(), null]) {
    await request(admin, path + '/assign', { assignedAccountId: admin.id, ...(dueAt === undefined ? {} : { dueAt }) }, 400);
  }
  await request(admin, path + '/assign', { assignedAccountId: admin.id, dueAt: deadline(), status: 'CLOSED' }, 400);
  await request(admin, path + '/wait', { message: 'Invalid before assignment' }, 400);
  await request(admin, path + '/resolve', { message: 'Invalid before assignment' }, 400);
  await request(customer, responsePath(id), { decision: 'ACCEPT', message: 'Invalid before resolution' }, 400);
  assert.equal((await state(id)).status, 'OPEN'); assert.equal((await state(id)).dueAt, null);
  assert.equal(await auditCount(id), 1);

  const withOffset = deadline().replace('Z', '+03:00');
  const assigned = await request(admin, path + '/assign', { assignedAccountId: admin.id, dueAt: withOffset });
  assert.equal(assigned.status, 'ASSIGNED'); assert.equal(assigned.assignedAccountId, admin.id);
  assert.equal(new Date(assigned.dueAt).getTime(), Date.parse(withOffset)); assert.equal(assigned.overdue, false);
  const beforeReplay = await auditCount(id);
  await request(admin, path + '/assign', { assignedAccountId: admin.id });
  assert.equal(await auditCount(id), beforeReplay, 'same assignment replay must not create a duplicate audit');
  await request(peer, path + '/resolve', { message: 'Not the assigned resolver' }, 400);
  await request(admin, path + '/wait', { message: 'Please provide the reference for this synthetic request.' });
  assert.equal((await state(id)).status, 'WAITING_CUSTOMER');
  await request(other, `/customer-service/cases/${id}/replies`, { message: 'Another account' }, 404);
  await request(customer, `/customer-service/cases/${id}/replies`, { message: 'Synthetic reference supplied.' });
  const expired = new Date(Date.now() - 10000);
  await db.customerCase.update({ where: { id }, data: { dueAt: expired } });
  assert.equal((await request(admin, path)).overdue, true);
  const escalated = await request(admin, path + '/escalate', { assignedAccountId: peer.id, message: 'Synthetic escalation to the responsible reviewer.' });
  assert.equal(escalated.status, 'ASSIGNED'); assert.equal(escalated.assignedAccountId, peer.id);
  assert.equal(escalated.escalationRoute, 'FINANCE'); assert.equal(escalated.overdue, true);
  assert.equal(new Date(escalated.dueAt).getTime(), expired.getTime(), 'escalation must preserve the explicit overdue deadline unless changed');
  const extended = await request(peer, path + '/assign', { assignedAccountId: peer.id, dueAt: deadline() });
  assert.equal(extended.overdue, false);
  await request(admin, path + '/resolve', { message: 'Previous assignee no longer resolves this case' }, 400);
  await request(peer, path + '/resolve', { message: 'Synthetic payment issue investigated; no payment was executed.' });
  assert.equal((await state(id)).status, 'RESOLVED');
  await request(peer, path + '/close', { message: 'Administrative bypass is not a route' }, 404);
  await request(other, responsePath(id), { decision: 'ACCEPT', message: 'Not the requester' }, 404);
  await request(customer, responsePath(id), { decision: 'OBJECT', message: 'The synthetic reference still needs correction.' });
  assert.equal((await state(id)).status, 'ASSIGNED'); assert.equal((await state(id)).assignedAccountId, peer.id);
  await request(peer, path + '/resolve', { message: 'Corrected synthetic resolution after customer objection.' });
  const accepted = await request(customer, responsePath(id), { decision: 'ACCEPT', message: 'I accept this synthetic resolution.' });
  assert.equal(accepted.status, 'CLOSED'); assert.equal(accepted.overdue, false);
  await request(customer, `/customer-service/cases/${id}/replies`, { message: 'Closed cases cannot receive a new reply.' }, 400);
  await request(peer, path + '/assign', { assignedAccountId: peer.id, dueAt: deadline() }, 400);
  const detail = await request(admin, path);
  assert(detail.history.some(row => row.action === 'customer_case.resolution_objected'));
  const acceptance = detail.history.find(row => row.action === 'customer_case.resolution_accepted');
  assert.equal(acceptance.actorId, customer.personId);
  const escalation = detail.history.find(row => row.action === 'customer_case.escalate');
  assert.equal(escalation.actorId, admin.personId); assert.equal(escalation.metadata.escalationRoute, 'FINANCE');
  assert.equal(escalation.metadata.previousAssignedAccountId, admin.id); assert.equal(escalation.metadata.assignedAccountId, peer.id);
  assert.equal(detail.interactions.filter(row => row.actorType === 'STAFF').length, 4);
  assert(!(await request(other, '/customer-service/cases/mine')).some(row => row.id === id));

  // Owner membership and organization scope are checked again for every response.
  const orgCase = await createCase(customer, 'SUPPORT', org.id), orgPath = management(orgCase.id);
  await request(admin, orgPath + '/assign', { assignedAccountId: admin.id, dueAt: deadline() });
  await request(admin, orgPath + '/resolve', { message: 'Synthetic organization resolution.' });
  const requesterList = await request(customer, `/organizations/${org.id}/requests`);
  const otherList = await request(other, `/organizations/${org.id}/requests`);
  assert.equal(requesterList.items.find(row => row.id === orgCase.id).canRespondToResolution, true);
  assert.equal(otherList.items.find(row => row.id === orgCase.id).canRespondToResolution, false);
  assert.equal('customerId' in requesterList.items.find(row => row.id === orgCase.id), false);
  await request(customer, responsePath(orgCase.id), { decision: 'ACCEPT', message: 'Wrong personal endpoint' }, 404);
  await request(other, responsePath(orgCase.id, org.id), { decision: 'ACCEPT', message: 'Same organization, different requester' }, 404);
  await request(staff, responsePath(orgCase.id, orgB.id), { decision: 'ACCEPT', message: 'Other organization' }, 404);
  await db.organization.update({ where: { id: org.id }, data: { status: 'SUSPENDED' } });
  await request(customer, responsePath(orgCase.id, org.id), { decision: 'ACCEPT', message: 'Suspended organization' }, 403);
  await db.organization.update({ where: { id: org.id }, data: { status: 'ACTIVE' } });
  await db.organizationMember.update({ where: { organizationId_accountId: { organizationId: org.id, accountId: customer.id } }, data: { role: 'VIEWER' } });
  await request(customer, responsePath(orgCase.id, org.id), { decision: 'ACCEPT', message: 'Read-only requester' }, 403);
  await db.organizationMember.update({ where: { organizationId_accountId: { organizationId: org.id, accountId: customer.id } }, data: { role: 'OWNER' } });
  await request(customer, responsePath(orgCase.id, org.id), { decision: 'ACCEPT', message: 'Organization requester accepts.' });
  await request(customer, `/organizations/${org.id}/requests/${orgCase.id}/replies`, { message: 'Reply after closure' }, 400);

  // Simultaneous resolutions and customer acceptance commit once on real PostgreSQL.
  const race = await createCase(customer), racePath = management(race.id);
  await request(admin, racePath + '/assign', { assignedAccountId: admin.id, dueAt: deadline() });
  async function concurrent(path, actor, body) {
    const results = await Promise.all([1, 2].map(() => fetch(base + path, { method: 'POST', headers: { authorization: 'Bearer ' + actor.token, 'content-type': 'application/json' }, body: JSON.stringify(body) })));
    assert.deepEqual(results.map(result => result.status).sort(), [201, 400]);
    await Promise.all(results.map(result => result.arrayBuffer()));
  }
  await concurrent(racePath + '/resolve', admin, { message: 'Concurrent synthetic resolution.' });
  assert.equal(await auditCount(race.id, 'customer_case.resolve'), 1);
  await concurrent(responsePath(race.id), customer, { decision: 'ACCEPT', message: 'Concurrent explicit acceptance.' });
  assert.equal(await auditCount(race.id, 'customer_case.resolution_accepted'), 1);
  assert.equal((await state(race.id)).interactions.length, 3);

  // PostgreSQL audit rejection must roll back state, deadline and interaction together.
  const atomic = await createCase(customer), atomicPath = management(atomic.id);
  for (const step of [
    { action: 'customer_case.assign', actor: admin, path: atomicPath + '/assign', body: { assignedAccountId: admin.id, dueAt: deadline() } },
    { action: 'customer_case.resolve', actor: admin, path: atomicPath + '/resolve', body: { message: 'Atomic synthetic solution.' } },
    { action: 'customer_case.resolution_accepted', actor: customer, path: responsePath(atomic.id), body: { decision: 'ACCEPT', message: 'Atomic synthetic acceptance.' } },
  ]) {
    const before = await state(atomic.id), count = await auditCount(atomic.id);
    await injectAuditFailure(atomic.id, step.action);
    await request(step.actor, step.path, step.body, 500);
    assert.deepEqual(await state(atomic.id), before); assert.equal(await auditCount(atomic.id), count);
    await clearAuditFailure(); await request(step.actor, step.path, step.body);
  }

  // Generic case routes cannot decide, close, reassign or append to provider appeals.
  const protectedCase = await db.customerCase.create({ data: { customerId: customer.id, organizationId: org.id, type: 'QUESTION', status: 'RESOLVED',
    subject: 'Synthetic independent provider appeal', description: 'Dedicated workflow fixture', referenceType: 'PROVIDER_QUALITY_TRIP_REHEARSAL_V1', referenceId: 'synthetic-provider-reference', assignedAccountId: admin.id } });
  cases.push(protectedCase.id);
  await request(admin, management(protectedCase.id), undefined, 409);
  for (const [action, body] of [['assign', { assignedAccountId: admin.id, dueAt: deadline() }], ['wait', { message: 'Generic wait' }],
    ['resolve', { message: 'Generic resolution' }], ['escalate', { assignedAccountId: peer.id, dueAt: deadline(), message: 'Generic escalation' }]]) {
    await request(admin, management(protectedCase.id) + '/' + action, body, 409);
  }
  await request(customer, responsePath(protectedCase.id, org.id), { decision: 'ACCEPT', message: 'Generic acceptance' }, 409);
  await request(customer, `/organizations/${org.id}/requests/${protectedCase.id}/replies`, { message: 'Generic reply' }, 409);
  await request(customer, '/customer-service/cases', { type: 'QUESTION', subject: 'Reserved reference', description: 'Invalid generic entry', referenceType: 'PROVIDER_QUALITY_TRIP_REHEARSAL_V1', referenceId: 'synthetic' }, 400);
  assert.equal((await state(protectedCase.id)).status, 'RESOLVED'); assert.equal(await auditCount(protectedCase.id), 0);
  const queue = await request(admin, '/customer-service/admin/cases?page=1&pageSize=50');
  assert(!queue.items.some(row => row.id === protectedCase.id)); assert(queue.items.some(row => row.id === id));
  await request(admin, '/customer-service/admin/cases?page=0', undefined, 400);

  console.log('Customer-case HTTP/PostgreSQL lifecycle passed: verified admin assignment, explicit UTC/offset deadlines, overdue indication, existing escalation routing, assigned resolution, requester objection and acceptance before closure, tenant/member isolation, closed-reply denial, concurrent once-only transitions, audit rollback, and provider-appeal crossover denial. No external messages, default SLA duration or financial action.');
} finally {
  await clearAuditFailure().catch(() => {});
  const accountIds = accounts.map(row => row.id), personIds = accounts.map(row => row.personId), organizationIds = organizations.map(row => row.id);
  await db.auditEvent.deleteMany({ where: { OR: [{ actorId: { in: personIds } }, { resource: 'CustomerCase', resourceId: { in: cases } }] } }).catch(() => {});
  await db.customerCase.deleteMany({ where: { customerId: { in: accountIds } } }).catch(() => {});
  await db.organizationMember.deleteMany({ where: { organizationId: { in: organizationIds } } }).catch(() => {});
  await db.organization.deleteMany({ where: { id: { in: organizationIds } } }).catch(() => {});
  await db.session.deleteMany({ where: { accountId: { in: accountIds } } }).catch(() => {});
  await db.roleAssignment.deleteMany({ where: { accountId: { in: accountIds } } }).catch(() => {});
  await db.account.deleteMany({ where: { id: { in: accountIds } } }).catch(() => {});
  await db.person.deleteMany({ where: { id: { in: personIds } } }).catch(() => {});
  await db.$disconnect();
}
