import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
const url = new URL(process.env.DATABASE_URL || 'postgresql://invalid/invalid');
if (process.env.CI !== 'true' || process.env.NODE_ENV !== 'test' || !['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname) || !url.pathname.endsWith('_weather_ci')) throw new Error('Requires CI + NODE_ENV=test + isolated loopback *_weather_ci database.');
const require = createRequire(import.meta.url);
const { DatabaseService } = require('../dist/database/database.service');
const { AuditService } = require('../dist/audit/audit.service');
const { TripWeatherReviewService } = require('../dist/trips/trip-weather-review.service');
const { WeatherGateService } = require('../dist/trips/weather-gate.service');
const db = new DatabaseService(), realAudit = new AuditService(db), gate = new WeatherGateService({}, {});
let checks = 0, providerCalls = 0, failAudit = false;
const check = (ok, label) => { assert.ok(ok, label); checks++; console.log('PASS', label); };
const conflict = async (fn, label, status = 409) => { await assert.rejects(fn, e => e.getStatus?.() === status, label); checks++; console.log('PASS', label); };
global.fetch = async () => { throw new Error('Network/provider calls prohibited in local DB regression.'); };
let source;
const provider = { snapshot: async () => { providerCalls++; return typeof source === 'function' ? source() : structuredClone(source); } };
const service = new TripWeatherReviewService(db, provider, { record: async (event, tx) => { assert.ok(tx, 'Audit must share the transaction'); await realAudit.record(event, tx); if (failAudit) throw new Error('Isolated audit failure'); } });
try {
  const sql = readFileSync(new URL('../prisma/migrations/20260925210500_trip_weather_runtime/migration.sql', import.meta.url), 'utf8');
  for (const statement of sql.split(';').map(s => s.trim()).filter(Boolean)) await db.$executeRawUnsafe(statement);
  const actor = await db.account.create({ data: { email: `weather-${randomUUID()}@example.invalid`, passwordHash: 'not-a-login', status: 'ACTIVE', person: { create: { firstName: 'Offline', lastName: 'Weather' } } } });
  const role = await db.roleAssignment.create({ data: { accountId: actor.id, role: 'ADMIN', status: 'ACTIVE', scope: {} } });
  const startsAt = new Date(Date.now() + 2 * 86400000), endsAt = new Date(startsAt.getTime() + 3600000);
  const trip = await db.trip.create({ data: { title: 'Isolated weather DB fixture', type: 'TEST', status: 'OPEN', capacity: 1, startsAt, endsAt } });
  source = { provider: 'STORMGLASS', observedAt: startsAt.toISOString(), windSpeedKph: 0, waveHeightM: 0.5 };
  await service.setLocation(actor.id, trip.id, { locationName: 'A', latitude: 0, longitude: 0 });
  let review = (await service.refresh(actor.id, trip.id)).review;
  check(review.status === 'PENDING' && !review.requiresRefresh && review.decisionToken, 'real SQL refresh persists valid bound pending snapshot');
  check(review.snapshot.forecastContext.latitude === 0, 'zero coordinates preserved in immutable context');
  const decide = token => service.decide(actor.id, trip.id, { status: 'APPROVED', expectedReview: token });
  await conflict(() => decide(undefined), 'missing decision token rejected');
  review = (await decide(review.decisionToken)).review;
  check(review.status === 'APPROVED' && review.reviewedAt, 'exact raw timestamp CAS approves current forecast');
  check(!gate.evaluateReview(review.snapshot, review.status, { enabled: true, mode: 'ENFORCE', provider: 'STORMGLASS' }, review.context, review.fetchedAt).blocking, 'approved canonical review satisfies unchanged weather gate');
  const beforeRefresh = review;
  review = (await service.refresh(actor.id, trip.id)).review;
  check(review.status === 'APPROVED' && review.snapshotHash === beforeRefresh.snapshotHash, 'identical forecast/context preserves approval');
  await conflict(() => decide(beforeRefresh.decisionToken), 'refresh invalidates stale reviewer token');

  await db.$executeRaw`UPDATE "TripWeatherReview" SET "updatedAt"='2000-01-01T00:00:00.123456Z'::timestamptz WHERE "id"::text=${review.id}`;
  const precise = await service.latest(trip.id);
  await db.$executeRaw`UPDATE "TripWeatherReview" SET "updatedAt"="updatedAt"+interval '1 microsecond' WHERE "id"::text=${review.id}`;
  const nextPrecise = await service.latest(trip.id);
  check(precise.updatedAt.getTime() === nextPrecise.updatedAt.getTime() && precise.revision !== nextPrecise.revision, 'raw revision retains changes hidden by JS millisecond Date');
  await conflict(() => decide(precise.decisionToken), 'one-microsecond stale token rejected');
  review = (await decide(nextPrecise.decisionToken)).review;
  check(review.status === 'APPROVED', 'new exact-microsecond token succeeds');

  const oldToken = review.decisionToken, calls = providerCalls;
  await service.setLocation(actor.id, trip.id, { locationName: 'B', latitude: 18.2, longitude: 42.5 });
  review = await service.latest(trip.id);
  check(review.status === 'PENDING' && review.requiresRefresh && review.decisionToken === null, 'location change invalidates old forecast without laundering approval');
  await conflict(() => decide(oldToken), 'old-location approval rejected');
  check(providerCalls === calls, 'approval never silently fetches a new unseen forecast');
  review = (await service.refresh(actor.id, trip.id)).review;
  review = (await decide(review.decisionToken)).review;
  check(review.status === 'APPROVED', 'new location requires fresh forecast and human approval');
  const changedStart = new Date(startsAt.getTime() + 86400000), changedEnd = new Date(endsAt.getTime() + 86400000);
  await db.trip.update({ where: { id: trip.id }, data: { startsAt: changedStart, endsAt: changedEnd } });
  check((await service.latest(trip.id)).requiresRefresh, 'trip-time change invalidates forecast context');
  await conflict(() => decide(review.decisionToken), 'old-trip-time approval rejected');
  source = { ...source, observedAt: changedStart.toISOString() };
  review = (await service.refresh(actor.id, trip.id)).review;

  const auditCount = await db.auditEvent.count({ where: { action: 'TRIP_WEATHER_APPROVED', resourceId: review.id } });
  const duplicate = await Promise.allSettled([decide(review.decisionToken), decide(review.decisionToken)]);
  check(duplicate.filter(r => r.status === 'fulfilled').length === 1 && duplicate.filter(r => r.status === 'rejected' && r.reason.getStatus?.() === 409).length === 1, 'two real concurrent reviewer decisions have one winner');
  check(await db.auditEvent.count({ where: { action: 'TRIP_WEATHER_APPROVED', resourceId: review.id } }) === auditCount + 1, 'concurrent loser leaves no false approval audit');
  source = { ...source, waveHeightM: 0.7 };
  review = (await service.refresh(actor.id, trip.id)).review;
  failAudit = true;
  await assert.rejects(() => decide(review.decisionToken), /Isolated audit failure/);
  failAudit = false;
  const afterRollback = await service.latest(trip.id);
  check(afterRollback.status === 'PENDING' && afterRollback.decisionToken === review.decisionToken, 'actual transaction rollback preserves pending state and revision');
  check(await db.auditEvent.count({ where: { action: 'TRIP_WEATHER_APPROVED', resourceId: review.id } }) === 0, 'actual transaction rollback removes inserted audit');
  await db.roleAssignment.update({ where: { id: role.id }, data: { status: 'SUSPENDED' } });
  await conflict(() => decide(review.decisionToken), 'revoked admin denied inside transaction', 403);
  await db.roleAssignment.update({ where: { id: role.id }, data: { status: 'ACTIVE' } });

  const baseline = source;
  source = async () => { await service.setLocation(actor.id, trip.id, { locationName: 'C', latitude: 20, longitude: 40 }); return baseline; };
  const beforeRace = await db.$queryRaw`SELECT count(*)::int AS n FROM "TripWeatherReview" WHERE "tripId"::text=${trip.id}`;
  await conflict(() => service.refresh(actor.id, trip.id), 'changed location during fetch discards stale response');
  check((await db.$queryRaw`SELECT count(*)::int AS n FROM "TripWeatherReview" WHERE "tripId"::text=${trip.id}`)[0].n === beforeRace[0].n, 'discarded response leaves no review row');
  source = baseline;
  review = (await service.refresh(actor.id, trip.id)).review;
  await db.$executeRaw`UPDATE "TripWeatherReview" SET "fetchedAt"=${new Date(Date.now() + 86400000)} WHERE "id"::text=${review.id}`;
  check((await service.latest(trip.id)).requiresRefresh, 'future fetched timestamp is unavailable, unlike legitimate future forecast');
  source = { ...source, waveHeightM: 0.9 };
  review = (await service.refresh(actor.id, trip.id)).review;
  check((await service.latest(trip.id)).id === review.id && !review.requiresRefresh, 'fresh revision recovers from older corrupt future fetchedAt');
  await db.$executeRaw`UPDATE "TripWeatherReview" SET "snapshot"="snapshot"-'forecastContext' WHERE "id"::text=${review.id}`;
  check((await service.latest(trip.id)).requiresRefresh, 'legacy missing binding cannot appear approved');
  await conflict(() => decide(review.decisionToken), 'legacy missing binding cannot be approved');
  source = { provider: 'STORMGLASS', observedAt: '2020-01-01T00:00:00Z', windSpeedKph: 3 };
  await conflict(() => service.refresh(actor.id, trip.id), 'outside-window historical forecast rejected', 503);
  check(await db.operationalSetting.count({ where: { key: 'WEATHER_GATE' } }) === 0, 'test never changes a weather policy setting');
  console.log(`Weather context PostgreSQL: ${checks} checks passed; real microsecond CAS, concurrency, rollback, legacy/context/future recovery; fixture provider only.`);
} finally { await db.$disconnect(); }
